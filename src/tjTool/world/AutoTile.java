    boolean checkBuild(Building other);

    static TextureRegion[] atlasRegions(TextureRegion region) {
        return atlasRegions(region, 32, 32, 64);
    }

    static TextureRegion[] atlasRegions(TextureRegion region, int tileWidth, int tileHeight, int offset) {
        int x = region.getX() + offset;
        int y = region.getY();
        int width = region.width - offset;
        int height = region.height;
        int widthTo = width + x;
        int heightTo = height + y;

        TextureRegion[] regions = new TextureRegion[(width / tileWidth + 1) * (height / tileHeight + 1)];
        int idx = 0;

        for (int arrY = y; arrY < heightTo; arrY += tileHeight)
            for (int arrX = x; arrX < widthTo; arrX += tileWidth)
                regions[idx++] = new TextureRegion(region.texture, arrX, arrY, tileWidth, tileHeight);

        return regions;
    }

    static TextureRegion atlasLarge(TextureRegion region) {
        return new TextureRegion(region.texture, region.getX(), region.getY(), 64, 64);
    }

    static TextureRegion atlasUI(TextureRegion region) {
        return new TextureRegion(region.texture, region.getX(), region.getY() + 64, 64, 64);
    }

    default int getIndex4(Building building) {
        return getIndex(building, d4);
    }

    default int getIndex8(Building building) {
        return getIndex(building, d8);
    }

    default int getIndex(Building building, Point2[] geometry) {
        int index = 0;
        for (int i = 0; i < geometry.length; i++)
            if (checkBuild(world.build(building.tile.x + geometry[i].x, building.tile.y + geometry[i].y)))
                index |= 1 << i;
        return index;
    }

